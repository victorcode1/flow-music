class RadioCountry {
  const RadioCountry({
    required this.code,
    required this.name,
    required this.latitude,
    required this.longitude,
    required this.south,
    required this.west,
    required this.north,
    required this.east,
    this.stationCount,
  });

  final String code;
  final String name;
  final double latitude;
  final double longitude;
  final double south;
  final double west;
  final double north;
  final double east;
  final int? stationCount;

  bool intersects({
    required double boundsSouth,
    required double boundsWest,
    required double boundsNorth,
    required double boundsEast,
  }) {
    final latOverlap = south <= boundsNorth && north >= boundsSouth;
    if (!latOverlap) return false;

    if (boundsWest <= boundsEast) {
      return west <= boundsEast && east >= boundsWest;
    }

    return west <= boundsEast || east >= boundsWest;
  }

  double distanceScore(double latitude, double longitude) {
    final dLat = this.latitude - latitude;
    final dLng = this.longitude - longitude;
    return dLat * dLat + dLng * dLng;
  }

  RadioCountry copyWith({
    String? code,
    String? name,
    double? latitude,
    double? longitude,
    double? south,
    double? west,
    double? north,
    double? east,
    int? stationCount,
  }) {
    return RadioCountry(
      code: code ?? this.code,
      name: name ?? this.name,
      latitude: latitude ?? this.latitude,
      longitude: longitude ?? this.longitude,
      south: south ?? this.south,
      west: west ?? this.west,
      north: north ?? this.north,
      east: east ?? this.east,
      stationCount: stationCount ?? this.stationCount,
    );
  }
}

